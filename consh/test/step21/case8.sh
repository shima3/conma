# 段階 B9：エラーの位置は、(( )) の中の、失敗した所（スクリプトの行と桁）
(( o = { a: null } ))
(( x = 1 + o.a.b ))
echo "status $?"
# 複数の行の (( )) と、その中で作った関数をコマンドとして呼んだときのエラー（関数を作った (( )) の中の位置）
(( f = (v) => {
  const t = v.list
  return t.length
} ))
$(( f )) 5
echo "status $?"
# 同じ (( )) を別の場所で動かしたときは、その場所
(( g = () => o.a.z ))
$(( g ))
(( g = () => o.a.z ))
$(( g ))
# 語の中の $(( ))（スクリプトを終える）
echo "word $(( o.a.c ))"
